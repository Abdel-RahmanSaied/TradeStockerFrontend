test('mobile navigation, no fabricated returns and access clears on reload', async ({ page }) => {
  await page.setViewportSize({width:390,height:844});
  await page.getByRole('button',{name:'Market data',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Market data',exact:true})).toBeVisible();
  await expect(page.getByText('No live feed connected',{exact:true})).toBeVisible();
  await expect(page.getByText(/guaranteed profit|total return|win rate/i)).toHaveCount(0);
  await page.reload();
  await expect(page.getByRole('alert')).toContainText('Access denied. Check the local API token.');
  await expect(page.getByText('Waiting for the backend',{exact:true})).toBeVisible();
});
